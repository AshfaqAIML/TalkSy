/**
 * Regenerates `src/lib/generated/platform-stats.ts` — the client-safe
 * literal snapshot of `computePlatformStats()`. Run after adding content:
 *
 *   bun scripts/generate-platform-stats.ts
 *
 * `tests/platform-stats.test.ts` fails when the snapshot goes stale.
 */

import { mkdirSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { computePlatformStats } from "../src/lib/platform-stats";

const stats = computePlatformStats();

const OUT = resolve(__dirname, "../src/lib/generated/platform-stats.ts");
const body = `// AUTO-GENERATED by scripts/generate-platform-stats.ts — do not edit.
// Freshness is asserted by tests/platform-stats.test.ts.

export const PLATFORM_STATS = ${JSON.stringify(stats, null, 2)} as const;

export type PlatformStats = typeof PLATFORM_STATS;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body, "utf8");
console.log(`[stats] wrote ${OUT}`);
console.log(`[stats] ${JSON.stringify(stats)}`);
